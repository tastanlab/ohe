import os
import random
import pandas as pd
import numpy as np
import torch
import torch.nn as nn
from tqdm import tqdm

seed = 42
random.seed(seed)
np.random.seed(seed)
torch.manual_seed(seed)
torch.cuda.manual_seed_all(seed)
torch.backends.cudnn.deterministic = True
torch.backends.cudnn.benchmark = False

# Generate complex synergy scores using masked feature vectors.
# Two versions are produced:
# 1. Non-repeated dataset, special case where drug or cell line dont repeat across splits.
# 2. Standard dataset, used in all regular experiments (with all permutations and split strategies lpo lodo lco ldo)
# The scores are generated by concatenated masked features (Drug1, Drug2, CellLine) through an MLP.



combo_path = "/complex_experiment/non_repeated/synergy_scores_unique.csv"
drug_feat_path = "/complex_experiment/non_repeated/49000_drug_features_selected.csv"
cell_feat_path = "/complex_experiment/non_repeated/24500_cell_line_features_selected.csv"
output_path = "/complex_experiment/non_repeated/generated_scores_complex.txt"

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

combo_df = pd.read_csv(combo_path)
drug_feat_df = pd.read_csv(drug_feat_path, index_col=0)
cell_feat_df = pd.read_csv(cell_feat_path, index_col=0)

drug_feat_dict = drug_feat_df.to_dict(orient="index")
cell_feat_dict = cell_feat_df.to_dict(orient="index")


class PseudoSynergyMLP(nn.Module):
    def __init__(self, input_dim):
        super(PseudoSynergyMLP, self).__init__()
        self.net = nn.Sequential(
            nn.Linear(input_dim, 256),
            nn.ReLU(), 
            nn.Linear(256, 128),
            nn.ReLU(),
            nn.Linear(128, 1)
        )

    def forward(self, x):
        return self.net(x)



# calculate input dimension Drug1 + Drug2 + CellLine
feature_dim = len(next(iter(drug_feat_dict.values()))) * 2 + len(next(iter(cell_feat_dict.values())))
model = PseudoSynergyMLP(input_dim=feature_dim).to(device)
model.eval()

scores = []

for _, row in tqdm(combo_df.iterrows(), total=len(combo_df)):
    d1 = row['Drug_1']
    d2 = row['Drug_2']
    cl = row['CellLine']

    d1_feat = np.array(list(drug_feat_dict[d1].values()))
    d2_feat = np.array(list(drug_feat_dict[d2].values()))
    cl_feat = np.array(list(cell_feat_dict[cl].values()))

    x = np.concatenate([d1_feat, d2_feat, cl_feat])
    x_tensor = torch.tensor(x, dtype=torch.float32).unsqueeze(0).to(device)

    with torch.no_grad():
        score = model(x_tensor).item() * 200
    scores.append(score)


with open(output_path, "w") as f:
    for s in scores:
        f.write(f"{s}\n")


